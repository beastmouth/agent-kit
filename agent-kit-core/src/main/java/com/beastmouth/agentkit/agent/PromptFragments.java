package com.beastmouth.agentkit.agent;

/**
 * 两套引擎共用的提示词片段。
 *
 * <p><b>为什么必须抽出来共用</b>：{@code legacy} 与 {@code agentscope} 是同一份业务、
 * 同一批子 Agent、同一套工具的二选一实现。回复风格、Markdown 用法这些约束
 * 属于<b>产品口径</b>，不是某个引擎的实现细节——各写一份必然分叉：改了 legacy 忘了新引擎，
 * 用户看到的就是「同样的问句，切个引擎回答风格就变了」，而这种不一致在做 A/B 时
 * 会被误读成「引擎能力差异」。</p>
 *
 * <p>这里只放<b>与业务无关</b>的通用约定。业务侧的口径（术语、单位、行业规范、
 * 禁止行为）通过 {@code agent-kit.extra-instructions} 追加，不要改这几个常量——
 * 它们是所有使用方共享的地基。</p>
 *
 * <p>{@link #PROTOCOL} 只给 legacy 用：另一套引擎走模型原生的 function calling，
 * 不需要让模型自己拼 JSON 协议。但 {@link #REPLY_STYLE} 两边都要——原生 tool_calls
 * 解决的是「怎么调工具」，不解决「调完之后话该怎么说」。</p>
 */
public final class PromptFragments {

    private PromptFragments() {
    }

    /**
     * 工具调用协议（仅 legacy 引擎使用）。
     *
     * <p>不依赖厂商的 {@code tool_calls} 报文，而是让模型输出固定结构的 JSON，
     * 好处是任意模型（包括不支持原生 function calling 的推理模型）都能用。</p>
     */
    public static final String PROTOCOL = """

            输出协议（必须严格遵守，违反会被解析失败）：
            1. 只输出一个 JSON 对象，不要 markdown 代码块，不要任何解释文字。
            2. 需要调用工具时输出：{"tools":[{"tool":"工具名","args":{参数对象}}]}
               数组里可以放多个工具，执行顺序就是数组顺序；只有一个工具时写成
               {"tool":"工具名","args":{...}} 也可以，两种写法等价。
            3. 不需要调用工具、或已经拿到结果时输出：{"tool":null,"reply":"给用户看的话"}
            4. 必填参数不全时不要调用工具，用 reply 反问用户缺失的信息。
            5. 严禁编造执行结果；某个操作是否成功，只能依据「工具结果」。
            """;

    /**
     * 回执真实性规则（两套引擎共用）。
     *
     * <p><b>为什么必须存在</b>：会话历史里躺着多组「用户提要求 → 助手『已完成』」的样例，
     * 而历史只渲染最终文本、不带工具调用痕迹。模型会做完美的上下文模仿——这次也直接答
     * 「已完成」，跳过工具，用户以为办好了，实际什么都没发生。事后核查表明这不是降级
     * 也不是小模型的锅，主模型同样会犯：只要历史里「成功回执」看起来不需要工具就能说出口。</p>
     *
     * <p>与引擎层的空口回执守门配套：这里管「事前劝」，守门管「事后拦」，两条腿缺一不可。</p>
     */
    public static final String TOOL_TRUTH = """

            回执真实性（违反此条比答错任何问题都严重）：
            - 「已完成/已记录/已添加/已删除/已修改」这类完成回执，只能在你本轮真实调用过
              对应工具、且工具返回成功之后才能说。没调工具就说出这类话，等于欺骗用户。
            - 历史对话里的回执都是当时调用工具之后才产生的，不是凭空说出来的；
              禁止因为历史里有类似回复，就跳过工具直接模仿着作答。
            - 查询类结论同理：任何具体数字、清单必须来自本轮工具返回的数据，
              没有数据支撑不得编造。
            """;

    /**
     * 回复风格。放在共用片段而不是各子 Agent 的提示词里，是为了让所有领域共用一套
     * 输出规范：网页、IM、CLI 各端都按 Markdown 渲染，模型只要按结构写就各端都好看。
     *
     * <p>同时它也是<b>控制输出长度</b>的手段：「一句话能说清就直接说」「不要加标题、
     * 不要加粗」直接压掉了模型爱写小标题的倾向。缺了这段，模型会自行发挥成
     * 「一、结论 二、明细 三、建议」的三段式，输出 token 翻倍而信息量不变。</p>
     */
    public static final String REPLY_STYLE = """

            回复风格（用户会在网页、IM、CLI 等端看到，各端都按 Markdown 渲染）：
            - 一句话能说清的（一次操作结果、一个合计数字）就直接说，不要加标题、不要列表、不要加粗。
            - 有多项内容（明细清单、分类构成、对比、走势）时用 Markdown：
              先用一行写结论，再用「- 」列表或用表格（不超过 4 列）列明细。
            - 一句话里有多个诉求（「昨天多少，明细是什么」）时，先用 tools 一次把
              统计和明细都取回来，再按「结论 → 明细」的顺序组织成一条回答，不要分两条发。
            - 同一段回答里数字格式保持一致（小数位、单位、千分位要么都用要么都不用）。
            - 不要输出 JSON，不要提工具名，不要解释你调用了什么。
            """;
}
